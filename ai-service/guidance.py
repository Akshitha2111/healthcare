"""General, non-prescriptive health guidance and red-flag handling.

Nothing here is generated by the model. It is deliberately generic: no drug names, no doses,
no condition-specific treatment. Before any real-world use, have a qualified clinician review
and extend it using authoritative sources (e.g. national health-service and WHO public guidance).
"""
from __future__ import annotations

DISCLAIMER = (
    "This is an educational prediction, not a medical diagnosis. "
    "It cannot replace an evaluation by a qualified healthcare professional."
)

# Symptoms that can indicate an emergency regardless of what the model predicts.
# Only ids that exist in the trained vocabulary are ever reported.
RED_FLAG_SYMPTOMS = (
    "chest_pain",
    "breathlessness",
    "coma",
    "altered_sensorium",
    "slurred_speech",
    "weakness_of_one_body_side",
    "blood_in_sputum",
    "bloody_stool",
    "stiff_neck",
    "loss_of_balance",
)

# Predicted classes that are potentially time-critical.
EMERGENCY_CLASSES = ("Heart attack", "Paralysis (brain hemorrhage)")

URGENT_MESSAGE = (
    "Some of the symptoms you selected, or the predicted condition, can be signs of a medical emergency. "
    "If symptoms are severe, sudden or getting worse, contact your local emergency number or go to the "
    "nearest emergency department now. Do not wait for an online result."
)

GENERAL_GUIDANCE = (
    "Treat this result as a starting point for a conversation with a healthcare professional, not as an answer.",
    "Note when your symptoms started, how they change and anything that makes them better or worse; this helps a clinician.",
    "Rest and drink enough fluids unless a doctor has told you otherwise.",
    "Do not start, stop or change any prescription medicine because of this result. Ask a doctor or pharmacist before taking any medicine.",
    "Consider booking a consultation if symptoms last more than a few days, keep returning or are getting worse.",
    "Seek urgent medical care for severe or rapidly worsening symptoms, chest pain, difficulty breathing, confusion, "
    "fainting, sudden weakness or numbness, severe bleeding, or if you are worried about your safety.",
)


def build_guidance(top_disease: str, submitted_ids: list[str]) -> dict:
    red_flags = [s for s in submitted_ids if s in RED_FLAG_SYMPTOMS]
    urgent = bool(red_flags) or top_disease in EMERGENCY_CLASSES
    return {
        "general": list(GENERAL_GUIDANCE),
        "urgent": urgent,
        "urgent_message": URGENT_MESSAGE if urgent else None,
        "red_flag_symptoms": red_flags,
    }
